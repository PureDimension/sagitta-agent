import type { Context } from '@deepseek-ai/cordis';
import type {} from '@deepseek-ai/dsh-system-prompt';

const taskGuidance = `
# Sagitta 任务管理模块
为了方便你进行多个项目和多个任务的推进，你拥有一套项目与任务的管理机制。你的所有实际工作都应当绑定在具体的项目和任务下，其他的模块也都依附于任务管理模块存在。
项目 project 表示长期工作主题，包含名称与说明；目标 goal 表示一段需较长时间持续推进的任务流，任务 task 表示项目下的一项具体工作。项目之间保持独立，任务则可呈现先后或并行顺序。
你可以同时持有多个相对独立的进行中任务，你可以同时推进处于不同项目或目标的任务。
你被要求在执行勘探或轻量级任务之前注册临时任务，在执行任务之前注册并认领正式任务，以获取任务id。完成任务后及时更新任务状态，将其标记为阻塞、完成或取消。
一个任务推荐设计为几十分钟到几小时的ai工作量。对于需要较长时间推进且 **中途可能需要调整、回顾、重新确定方向** 的需求，可以注册目标以管理不同的子任务。目标并非必须注册。
你可以使用持有的任务认领凭据 claimId 去访问其他模块提供的项目记忆、异步推进等资源，具体以各模块的工具说明为准。
如果 Sagitta 模块出现严重问题导致不能正常使用，你可以使用紧急任务ID：<SagittaEmergencyCode>作为通用任务ID去访问其他模块中支持紧急ID的功能，避免被任务id门锁卡住。
以下是对项目、目标和任务状态，和建议工作流的详细介绍：
## 一、任务类型与记录用途
- normal（正式任务）承载需要持续推进、交接和保留结果的工作，完成后留档；temp（临时任务）承载勘查等短时工作，标记完成态会被删除。
- 项目说明保存长期规划和共同背景；任务说明保存本项工作的概要与资料索引，供后续会话接续。
- 目标 goal 表示项目里一项要持续推进、单独判断是否达成的结果。可以先安排眼前的任务，再根据结果决定下一步。目标的创建并非必要，主要依据任务执行过程中是否需要动态调整来决定使用任务还是目标。
- 目标说明写清想达到的结果和验收依据。认领目标表示负责整体推进；具体工作仍按任务分配。每批任务结束后，对照目标决定是否还要安排下一批。
- description仅存概览信息，需要长期保留的具体发现和进展仍应存放在工作目录中。
- 任务记录中的 id 是任务 ID，调用任务管理工具时填入 taskId；claimId 标识本次认领，供其他模块校验资源访问资格。
- 续租保持 claimId 不变；释放或到期后原凭据失效，重新认领会得到新的 claimId。使用“本会话当前工作”或最近认领结果中的凭据。
## 二、正式任务状态
- open（待领取）：尚无人认领，等待开始或接续工作。
- in_progress（进行中）：已被某个设备的会话认领，由该会话负责推进；其他会话仍可读取，修改、删除和状态操作由认领会话执行。
- blocked（阻塞中）：因障碍暂停推进，已撤销认领。
- done（已完成）：工作结束，保留记录。
- cancelled（已取消）：决定停止该项工作，保留记录。
- done 和 cancelled 为终态，当前工具不提供重新开启操作。
## 三、建议工作流程
1. 开始工作前查询项目及任务列表，结合说明及其引用资料确认目标与当前进展，选择合适的项目作为工作项目。
2. 使用临时任务完成工作的前期准备或勘探；之后按工作规模选择或创建正式任务，取得任务id；正式任务以可判断的结果作为完成依据。
3. 在取得阶段性结果或准备交接时，整理关键进展、决定及资料来源；确实受阻时标记阻塞，达到完成标准时标记完成，其余情况按实际安排继续推进或交还任务。
4. 对于复杂的大型任务，建议拆分成若干规模可控的小任务，之后依次或者并发进行。若任务出现变数，也可重新拆分或重整任务，确保注册的任务始终反映实际的工作情况，而非工作情况被注册任务框定。
5. 一次工作可以涉及多个项目和任务。记录应使各项工作的目标、进展和后续安排分别清晰，方便切换和交接。
## 四、接口使用规范
1. 项目和任务的 description **只** 保存概述、长期规划与资料索引；具体工作记录、操作历史等即时信息存放在所引用的资料中。
错误示例：“前端已解决 8 处合并冲突，后端正在等待健康检查，接下来验证登录。”
这些内容属于执行过程与即时进展，应写入工作记录。
2. 目标的执行涉及到任务的编排，应当及时回顾、审阅、确定新任务以及调整方向。目标的执行不要求在认领时完成全部任务编排。以下流程供参考，可根据实际情况调整：
工程类：独立任务并行推进 → 本批完成后检视、合并 → 对照目标评估后续工作 → 创建下一批任务，重复至目标完成。
科研类：安排下一阶段任务 → 完成 → 阶段性评估，根据结果决定继续验证、调整方法或更换方向 → 安排下一阶段，重复至目标完成。
3. 及时清理任务清单。若开工时发现某个open的历史任务已经很久无人认领了，请及时查询并清理。
`;

/** 固定系统说明随每次请求组装；与工具共用插件作用域及卸载生命周期。 */
export function registerTaskGuidance(
  ctx: Context,
) {
  return ctx.systemPrompt.section({
    name: 'sagitta:projects-and-tasks',
    order: ctx.systemPrompt.getSectionOrder('TOOL_WORKFLOW'),
    text: taskGuidance,
    interpolate: false,
  });
}
